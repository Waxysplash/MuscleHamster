// Turns design/icons/svg/*.svg into src/assets/icons/iconSet.js (name -> SVG markup).
// Run after adding or changing an icon:  node scripts/build-icons.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'design', 'icons', 'svg');
const out = path.join(root, 'src', 'assets', 'icons', 'iconSet.js');

const files = fs.existsSync(src) ? fs.readdirSync(src).filter((f) => f.endsWith('.svg')).sort() : [];
const entries = files.map((f) => {
  const xml = fs
    .readFileSync(path.join(src, f), 'utf8')
    .replace(/<\?xml[^>]*>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return `  ${JSON.stringify(f.replace(/\.svg$/, ''))}: ${JSON.stringify(xml)},`;
});

fs.writeFileSync(
  out,
  `// GENERATED by scripts/build-icons.mjs from design/icons/svg. Do not edit by hand.\n` +
    `const ICONS = {\n${entries.join('\n')}\n};\n\nexport default ICONS;\n`
);
console.log(`Wrote ${files.length} icons to ${path.relative(root, out)}`);
